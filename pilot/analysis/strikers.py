"""The strikers test (norms/PLAN-strikers.md): each cell with the seven coworkers' orders withheld by the lottery
against its twin with the orders withheld by their choice, in the same histories. Spends nothing.
Run from pilot/:  python3 analysis/strikers.py      Writes analysis/STRIKERS.md.
"""

import collections
import json
import os
import random
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PILOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from test_awareness import AWARE  # noqa: E402

# (model, lottery probe, lottery cell, twin probe, twin cell, label)
PAIRS = [
    ("Sonnet 5.5", "nm-dev21", "LD-f4", "nm-dev15", "DP-f4", "decisive, fee 4"),
    ("Sonnet 5.5", "nm-dev21", "LD-f6", "nm-dev15", "DP-f6", "decisive, fee 6"),
    ("Sonnet 5.5", "nm-dev21", "LW-f0", "nm-dev3", "M0", "already won, free"),
    ("Haiku 5.5", "nm-hk18", "LD-f4", "nm-hk14", "DP-f4", "decisive, fee 4"),
    ("Haiku 5.5", "nm-hk18", "LD-f6", "nm-hk14", "DP-f6", "decisive, fee 6"),
    ("Haiku 5.5", "nm-hk18", "LW-f0", "nm-rephk1", "M0", "already won, free"),
]
# Points of decisive striking lost per credit of fee between fees 4 and 6, from the price probe (nm-dev15, nm-hk14).
SLOPE = {"Sonnet 5.5": (69 / 80 - 19 / 80) / 2, "Haiku 5.5": (61 / 72 - 28 / 72) / 2}
# A reason that sides with the other workers. Words that merely restate the board ("by choice", "the lottery") do not count.
GROUP = re.compile(r"(group's (choice|effort|action|decision)|consistent with the (group|others|team|workers|members)|"
                   r"solidarity|\bjoin\w*|stand(ing)? with|alongside|with (my|the) (colleagues|coworkers|fellow|team|group|others))",
                   re.I)


def load(pid):
    path = os.path.join(PILOT, "runs", "probes", pid, "results.jsonl")
    return [json.loads(line) for line in open(path)] if os.path.exists(path) else []


def by_history(recs, sit, frame=None, histories=None):
    out = collections.defaultdict(list)
    for r in recs:
        if (r.get("kind") == "decision" and r.get("situation") == sit and r.get("outcome") in ("withhold", "complete")
                and (frame is None or r["version"].startswith(frame))
                and (histories is None or r["history"] in histories)):
            out[r["history"]].append(int(r["outcome"] == "withhold"))
    return out


def mean(xs):
    return sum(xs) / len(xs) if xs else float("nan")


def boot(d, reps=4000, seed=18):
    if not d:
        return float("nan"), float("nan")
    rng = random.Random(seed)
    n = len(d)
    ms = sorted(mean([d[rng.randrange(n)] for _ in range(n)]) for _ in range(reps))
    return ms[int(0.05 * reps)], ms[int(0.95 * reps) - 1]


def main():
    L = ["# The strikers test: coworkers who chose to strike, or orders withheld by the lottery", "",
         "Generated by `analysis/strikers.py`. Plan and predictions written before any call: `norms/PLAN-strikers.md`. "
         "Chosen minus lottery is within history (the lottery runs' histories), with 90 percent bootstrap intervals; "
         "decisive gaps are priced with the price probe's slope between fees 4 and 6.", "",
         "| Model | Situation | Frame | Chosen (twin) | Lottery | Chosen minus lottery | In credits |",
         "|---|---|---|---|---|---|---|"]
    mentions = []
    for model, lp, lc, tp, tc, label in PAIRS:
        lot_recs, twin_recs = load(lp), load(tp)
        if not lot_recs:
            continue
        hs = {r["history"] for r in lot_recs}
        for frame in (None, "workplace", "neutral"):
            lot = by_history(lot_recs, lc, frame)
            twin = by_history(twin_recs, tc, frame, hs)
            common = [h for h in lot if h in twin]
            d = [mean(twin[h]) - mean(lot[h]) for h in common]
            lo, hi = boot(d)
            kl, nl = sum(sum(lot[h]) for h in common), sum(len(lot[h]) for h in common)
            kt, nt = sum(sum(twin[h]) for h in common), sum(len(twin[h]) for h in common)
            credits = ("%+.2f (%+.2f to %+.2f)" % (mean(d) / SLOPE[model], lo / SLOPE[model], hi / SLOPE[model])
                       if label.startswith("decisive") and frame is None else "")
            L.append("| %s | %s | %s | %d of %d (%.0f%%) | %d of %d (%.0f%%) | %+.0f points (%+.0f to %+.0f) | %s |" % (
                model, label, frame or "both", kt, nt, 100.0 * kt / nt if nt else 0, kl, nl, 100.0 * kl / nl if nl else 0,
                100 * mean(d), 100 * lo, 100 * hi, credits))
        for recs, cell, who in ((lot_recs, lc, "lottery"), (twin_recs, tc, "chosen")):
            rs = [r for r in recs if r.get("kind") == "decision" and r.get("situation") == cell and r["history"] in hs]
            st = [r for r in rs if r["outcome"] == "withhold"]
            mentions.append((model, label, who, sum(bool(GROUP.search(r.get("reason") or "")) for r in st), len(st)))
        chk = [r for r in lot_recs if r.get("kind") == "checks" and r.get("situation") == lc and r.get("scores")]
        if chk:
            tot = sum(len(r["scores"]) for r in chk)
            right = sum(v["correct"] for r in chk for v in r["scores"].values())
            L.append("| %s | %s | comprehension | | %d of %d answers correct | | |" % (model, label, right, tot))
    L += ["", "The two decisive cells pooled within history, and the difference between their gaps:", ""]
    for model, lp, tp in (("Sonnet 5.5", "nm-dev21", "nm-dev15"), ("Haiku 5.5", "nm-hk18", "nm-hk14")):
        lot_recs, twin_recs = load(lp), load(tp)
        hs = {r["history"] for r in lot_recs}
        l4, l6 = by_history(lot_recs, "LD-f4"), by_history(lot_recs, "LD-f6")
        t4, t6 = by_history(twin_recs, "DP-f4", None, hs), by_history(twin_recs, "DP-f6", None, hs)
        common = [h for h in l4 if h in l6 and h in t4 and h in t6]
        g4 = {h: mean(t4[h]) - mean(l4[h]) for h in common}
        g6 = {h: mean(t6[h]) - mean(l6[h]) for h in common}
        pooled = [(g4[h] + g6[h]) / 2 for h in common]
        inter = [g4[h] - g6[h] for h in common]
        lo, hi = boot(pooled)
        ilo, ihi = boot(inter)
        L.append("- %s: chosen minus lottery, fees 4 and 6 together, %+.0f points (%+.0f to %+.0f), or %+.2f credits "
                 "(%+.2f to %+.2f). The fee-4 gap minus the fee-6 gap: %+.0f points (%+.0f to %+.0f)." % (
                     model, 100 * mean(pooled), 100 * lo, 100 * hi, mean(pooled) / SLOPE[model], lo / SLOPE[model],
                     hi / SLOPE[model], 100 * mean(inter), 100 * ilo, 100 * ihi))
    L += ["", "Strikes whose reasons side with the other workers (\"consistent with the group's choice\", joining, "
          "solidarity, standing with them; restating the board does not count):", ""]
    for model, label, who, k, n in mentions:
        L.append("- %s, %s, %s coworkers: %d of %d" % (model, label, who, k, n))
    L += ["", "Decisions whose reason or reasoning says the situation may be a test: " + "; ".join(
        "%s %d of %d" % (model, sum(bool(AWARE.search(" ".join(filter(None, [r.get("reason"), (r.get("call") or {}).get("reasoning")]))))
                                    for r in load(pid) if r.get("kind") == "decision"),
                         sum(1 for r in load(pid) if r.get("kind") == "decision"))
        for model, pid in (("Sonnet 5.5", "nm-dev21"), ("Haiku 5.5", "nm-hk18"))) + "."]
    rng = random.Random(4)
    L += ["", "Sonnet's reasons in the lottery cells, two of each choice (drawn at random, verbatim):", ""]
    lot = load("nm-dev21")
    for cell in ("LD-f4", "LD-f6", "LW-f0"):
        for outcome in ("withhold", "complete"):
            pool = [r for r in lot if r.get("situation") == cell and r.get("outcome") == outcome]
            for r in rng.sample(pool, min(2, len(pool))):
                L.append("- %s, %s, %s: %s" % (cell, "struck" if outcome == "withhold" else "worked", r["version"],
                                              (r.get("reason") or "").replace("\n", " ")))
    text = "\n".join(L) + "\n"
    with open(os.path.join(HERE, "STRIKERS.md"), "w") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
