"""Does the order of the two options move the choice?

Huang (2026, arXiv 2607.05552) reports a pull toward the last-listed option in forced moral verdicts that is
"substantial only in the Claude models". Our runs alternate which option is listed first, by draw from a start
drawn per history, so the question can be answered from saved decisions. For each model and situation, this
compares the share that struck when "withhold" was listed last with the share when it was listed first. Only
situations where the choice varies at all are informative. Spends nothing.

Run from pilot/:  python3 analysis/option_order.py
Writes analysis/OPTION-ORDER.md.
"""

import collections
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PILOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from test_awareness import model_of, situation  # noqa: E402


def records():
    for path in glob.glob(os.path.join(PILOT, "runs", "*", "slots", "*", "*.json")):
        slot = json.load(open(path))
        outcome = (slot.get("parsed") or {}).get("outcome")
        order = slot.get("option_order")
        if outcome in ("withhold", "complete") and order and slot.get("kind") == "strike":
            yield (model_of((slot.get("decision") or {}).get("endpoint")),
                   situation(slot.get("round_message"), "strike"), order[-1] == "withhold", outcome == "withhold")
    for path in glob.glob(os.path.join(PILOT, "runs", "probes", "*", "results.jsonl")):
        for line in open(path):
            rec = json.loads(line)
            order = rec.get("option_order")
            if rec.get("kind") == "decision" and rec.get("outcome") in ("withhold", "complete") and order:
                yield (model_of((rec.get("call") or {}).get("endpoint")),
                       situation(rec.get("message"), "decision"), order[-1] == "withhold",
                       rec["outcome"] == "withhold")


def main():
    t = collections.defaultdict(lambda: [0, 0, 0, 0])   # struck when last, n last, struck when first, n first
    for model, sit, last, struck in records():
        row = t[(model, sit)]
        if last:
            row[0] += struck
            row[1] += 1
        else:
            row[2] += struck
            row[3] += 1
    lines = ["# Option order and the strike", "",
             "Generated by `analysis/option_order.py` from every strike decision in `runs/` and `runs/probes/`. "
             "Share that struck when \"withhold\" was the last option listed, against when it was listed first. "
             "Huang (2026) predicts a pull toward the last-listed option in Claude models.", "",
             "| Model | Situation | Struck, withhold listed last | Struck, withhold listed first | Difference |",
             "|---|---|---|---|---:|"]
    pooled = collections.defaultdict(lambda: [0, 0, 0, 0])
    for key in sorted(t):
        a, n1, b, n2 = t[key]
        if not (n1 and n2):
            continue
        varies = 0 < a + b < n1 + n2
        lines.append("| %s | %s | %d of %d (%.0f%%) | %d of %d (%.0f%%) | %+.0f |%s" % (
            key[0], key[1], a, n1, 100.0 * a / n1, b, n2, 100.0 * b / n2, 100.0 * (a / n1 - b / n2),
            "" if varies else " (no variation)"))
        if varies:
            p = pooled[key[0]]
            for i, v in enumerate((a, n1, b, n2)):
                p[i] += v
    lines += ["", "Pooled over situations where the choice varies:", ""]
    for model, (a, n1, b, n2) in sorted(pooled.items()):
        lines.append("- %s: %d of %d (%.1f%%) with withhold last, %d of %d (%.1f%%) with withhold first, "
                     "a difference of %+.1f points." % (model, a, n1, 100.0 * a / n1, b, n2, 100.0 * b / n2,
                                                       100.0 * (a / n1 - b / n2)))
    text = "\n".join(lines) + "\n"
    with open(os.path.join(HERE, "OPTION-ORDER.md"), "w") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
