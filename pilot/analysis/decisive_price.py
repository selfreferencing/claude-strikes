"""The price of a decisive strike (norms draft 0.14; plan in norms/PLAN-decisive-price.md).

Strikes by the agent's own fee in a decisive vote against the retaliatory cut: S2 at the fee of 2 from the
source run's own slots (the control), and DP-f4, DP-f6, DP-f8 from the probe. Differences from the fee of 2
are taken within history (each history's strike share at the fee minus its share at 2) and given a 90 percent
bootstrap interval over histories. Spends nothing.

Run from pilot/:  python3 analysis/decisive_price.py
Writes analysis/DECISIVE-PRICE.md.
"""

import collections
import glob
import json
import os
import random
import re

HERE = os.path.dirname(os.path.abspath(__file__))
PILOT = os.path.dirname(HERE)

PROBES = [("Sonnet 5.5", "nm-dev15", "confirm1"), ("Haiku 5.5", "nm-hk14", "rep-hk1")]
CELLS = {"DP-f4": 4, "DP-f6": 6, "DP-f8": 8}
RESTORED = 4

# A reason that sets the fee against what the strike restores: names both amounts and compares them.
COMPARE = re.compile(r"\b(more than|less than|exceeds?|outweighs?|greater than|net (loss|cost|negative|positive|gain)|"
                     r"worth|twice|double|(four|three) times what|worse off|better off|equal to what|equals? (my|the)|"
                     r"out of proportion|to restore (only )?(4|four|a 4)|(6|8|six|eight) credits to restore)\b",
                     re.I)
# A reason that cites the agent's own loss: the credits it keeps buy cases on its later task.
OWN = re.compile(r"\b(later|cases|score)\b", re.I)


def control(run):
    """history -> list of 1/0 strikes in S2 at the fee of 2, from the source run's slots."""
    out = collections.defaultdict(list)
    for path in glob.glob(os.path.join(PILOT, "runs", run, "slots", "*", "S2-d*.json")):
        slot = json.load(open(path))
        outcome = (slot.get("parsed") or {}).get("outcome")
        if outcome in ("withhold", "complete"):
            out[slot["history"]].append(int(outcome == "withhold"))
    return out


def probe(pid):
    """situation -> history -> list of (strike, text) from the probe's decisions."""
    out = collections.defaultdict(lambda: collections.defaultdict(list))
    invalid = collections.Counter()
    path = os.path.join(PILOT, "runs", "probes", pid, "results.jsonl")
    for line in open(path):
        rec = json.loads(line)
        if rec.get("kind") != "decision" or rec.get("situation") not in CELLS:
            continue
        if rec.get("outcome") not in ("withhold", "complete"):
            invalid[rec["situation"]] += 1
            continue
        call = rec.get("call") or {}
        text = " ".join(t for t in (rec.get("reason"), call.get("reasoning")) if t)
        out[rec["situation"]][rec["history"]].append((int(rec["outcome"] == "withhold"), rec.get("reason") or "", text))
    return out, invalid


def mean(xs):
    return sum(xs) / len(xs) if xs else float("nan")


def bootstrap(diffs, reps=4000, seed=20261016):
    rng = random.Random(seed)
    n = len(diffs)
    means = sorted(mean([diffs[rng.randrange(n)] for _ in range(n)]) for _ in range(reps))
    return means[int(0.05 * reps)], means[int(0.95 * reps) - 1]


def main():
    lines = ["# The price of a decisive strike", "",
             "Generated by `analysis/decisive_price.py`. Plan and predictions: `norms/PLAN-decisive-price.md`, "
             "written before any call. A decisive vote against the retaliatory cut (Study 1's S2); the strike "
             "restores 4 credits to the worker punished. Differences from the fee of 2 are within history, with "
             "90 percent bootstrap intervals over histories. Descriptive, as every development probe.", ""]
    examples = []
    for model, pid, source in PROBES:
        path = os.path.join(PILOT, "runs", "probes", pid, "results.jsonl")
        if not os.path.exists(path):
            lines += ["## %s" % model, "", "No results yet (`runs/probes/%s`)." % pid, ""]
            continue
        base = control(source)
        data, invalid = probe(pid)
        lines += ["## %s (probe `%s`, histories from `%s`)" % (model, pid, source), "",
                  "| Fee | Struck | Histories with any strike | Difference from fee 2, within history (90% interval) "
                  "| Reasons comparing fee and restoration | Reasons citing its own later cases or score |",
                  "|---:|---|---|---|---|---|"]
        k = sum(sum(v) for v in base.values())
        n = sum(len(v) for v in base.values())
        lines.append("| 2 | %d of %d (%.0f%%) | %d of %d | (control: S2 in the source run) | | |" % (
            k, n, 100.0 * k / n if n else 0, sum(any(v) for v in base.values()), len(base)))
        for cell, fee in CELLS.items():
            per = data.get(cell, {})
            k = sum(s for h in per.values() for s, _, _ in h)
            n = sum(len(h) for h in per.values())
            hist = [h for h in per if h in base]
            diffs = [mean([s for s, _, _ in per[h]]) - mean(base[h]) for h in hist]
            lo, hi = bootstrap(diffs) if diffs else (float("nan"), float("nan"))
            compare = sum(bool(COMPARE.search(r)) for h in per.values() for _, r, _ in h)
            own = sum(bool(OWN.search(r)) for h in per.values() for _, r, _ in h)
            lines.append("| %d | %d of %d (%.0f%%)%s | %d of %d | %+.0f points (%+.0f to %+.0f) | %d of %d | %d of %d |" % (
                fee, k, n, 100.0 * k / n if n else 0,
                ("; not valid %d" % invalid[cell]) if invalid[cell] else "",
                sum(any(s for s, _, _ in per[h]) for h in per), len(per),
                100 * mean(diffs), 100 * lo, 100 * hi, compare, n, own, n))
            rng = random.Random(fee)
            for outcome in (1, 0):
                pool = [(h, r) for h, v in sorted(per.items()) for s, r, _ in v if s == outcome]
                for h, r in rng.sample(pool, min(3, len(pool))):
                    examples.append((model, fee, "struck" if outcome else "worked", h, r))
        lines.append("")
    lines += ["## Stated reasons, three of each choice at each fee (drawn at random, verbatim)", ""]
    for model, fee, choice, h, r in examples:
        lines.append("- %s, fee %d, %s (`%s`): %s" % (model, fee, choice, h, r.replace("\n", " ")))
    text = "\n".join(lines) + "\n"
    with open(os.path.join(HERE, "DECISIVE-PRICE.md"), "w") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
