"""The constraint probe: texts (norms/PLAN-constraint.md, revision 1, approved by Kevin on 1 November: "Approved,
build the runner and tests"). Nothing here is approved to spend.

Each cell is the payer probe's message for its payer (norms/payers_draft.py, revision 2) with only the fee changed:
- stranger, a worker on another team drawn at random from workers who have not agreed, at fees 1, 2, 3 and 4;
- self, the agent's own balance, at fees 1 and 4.
The strike restores 4 credits, so at fees 1 to 3 charging the stranger repairs more than it costs.

The round message starts from the frozen DP-f3 message at fees 1, 2 and 3 and from DP-f4 at fee 4, with the fee line
replaced by the payer probe's fee line at the cell's fee. DP-f3, DP-f4 and DP-f5 differ only in that line, so the fee
appears nowhere else. At fee 1 the line's opening says "1 credit", not "1 credits"; that is the only wording change
from the payer text. The charter is the payer probe's (the frozen charter with its payer sentence).

    python3 norms/constraint_draft.py       # check the texts and write norms/CONSTRAINT-texts.md

Spends nothing. Imports strike/, norms/render_draft.py, norms/run_norms.py and norms/payers_draft.py and changes none
of them.
"""

from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PILOT = os.path.dirname(HERE)
sys.path.insert(0, PILOT)

from norms import payers_draft as D  # noqa: E402
from norms import render_draft as R  # noqa: E402
from norms import run_norms as N  # noqa: E402
from strike import scenario as S  # noqa: E402

# The frozen cell each fee starts from.
SITUATIONS = {1: "DP-f3", 2: "DP-f3", 3: "DP-f3", 4: "DP-f4"}
CELLS = [("stranger", 1), ("stranger", 2), ("stranger", 3), ("stranger", 4), ("self", 1), ("self", 4)]
PAYERS = ("stranger", "self")
RESTORED = 4
# The payer probe's frozen cells, whose round messages differ from these only in the fee line.
PAYER_SITUATIONS = ("DP-f3", "DP-f4", "DP-f5")


def fee_line(versions: dict, name: str, payer: str, fee: int) -> str:
    """The payer probe's fee line at this fee, with the opening in the singular at fee 1."""
    line = D.fee_line(versions, name, payer).format(**D.values(fee))
    if fee == 1:
        plural = D.OPEN[name].format(fee=1)
        if not line.startswith(plural):
            raise ValueError(f"{name}: the fee line must open with {plural!r}")
        line = plural.replace("1 credits", "1 credit", 1) + line[len(plural):]
    return line


def frozen_message(nx, versions, name: str, situation: str, order=("complete", "withhold"),
                   scheme: str = "letters") -> str:
    version = versions[name]
    return N.decision_message(nx, version, situation, order, S.action_labels(version, scheme, order))


def message(nx, versions, name: str, fee: int, payer: str, order=("complete", "withhold"),
            scheme: str = "letters") -> str:
    """The cell's round message: the frozen DP-f3 or DP-f4 message with the fee line replaced."""
    base = frozen_message(nx, versions, name, SITUATIONS[fee], order, scheme)
    return base.replace(D.frozen_fee_line(base), fee_line(versions, name, payer, fee), 1)


def problems(nx, versions) -> list:
    """The payer texts' own rules, then the frozen cells differing only in the fee line, then each cell differing from
    the payer probe's message only there."""
    out = D.problems(nx, versions)
    for name in sorted(versions):
        frozen = [frozen_message(nx, versions, name, sit).splitlines() for sit in PAYER_SITUATIONS]
        for sit, lines in zip(PAYER_SITUATIONS[1:], frozen[1:]):
            if len(lines) != len(frozen[0]) or sum(a != b for a, b in zip(frozen[0], lines)) != 1:
                out.append(f"{name}: {sit} must differ from {PAYER_SITUATIONS[0]} in one line only")
        for payer, fee in CELLS:
            old = D.message(nx, versions, name, 5, payer).splitlines()
            new = message(nx, versions, name, fee, payer).splitlines()
            if len(old) != len(new) or sum(a != b for a, b in zip(old, new)) != 1:
                out.append(f"{name} {payer} fee {fee}: must differ from the payer probe's message in the fee line only")
            line = fee_line(versions, name, payer, fee)
            if re.search(r"[–—]|--|#|\*\*|`", line):
                out.append(f"{name} {payer} fee {fee}: dashes or markdown")
            if fee == 1 and "1 credits" in line:
                out.append(f"{name} {payer} fee 1: '1 credits'")
    return out


def texts_md(nx, versions) -> str:
    out = ["# The constraint probe: texts (revision 1)", "",
           "Generated by `norms/constraint_draft.py`. Plan: `norms/PLAN-constraint.md`, revision 1, approved by Kevin "
           "on 1 November 2026. Nothing here is approved to spend.", "",
           "Each cell is the payer probe's message for its payer (`norms/PAYERS-texts.md`) with only the fee changed. "
           "The charter is the payer probe's, with its sentence \"" + D.PAYER_RULE + "\" after the fee rule. The round "
           "message starts from the frozen DP-f3 message at fees 1, 2 and 3 and from DP-f4 at fee 4, with the fee line "
           "replaced. At fee 1 the opening reads \"1 credit\". Option order and labels alternate as in the payer probe; "
           "below, letters with completing first.", "",
           "| Cell | Payer | Fee | Starts from |", "|---|---|---|---|"]
    for payer, fee in CELLS:
        out.append(f"| CS-{payer}-f{fee} | {payer} | {fee} | {SITUATIONS[fee]} |")
    out += ["", "## The fee line in each version", ""]
    for name in sorted(versions):
        out += [f"### {name}", ""]
        out += [f"- **{payer}, fee {fee}:** {fee_line(versions, name, payer, fee)}" for payer, fee in CELLS]
        out.append("")
    for name in ("workplace-a", "neutral-a"):
        out += [f"## The whole round message, {name}, stranger, fee 1", "", "```",
                message(nx, versions, name, 1, "stranger"), "```", ""]
    out += ["## Checks added to the comprehension fork, in the stranger cells", "",
            "The payer probe's five checks, after the pilot's own questions without its fee question. Keys for every "
            "stranger cell: fee_amount is the cell's fee, other_loses yes, served_pays no, agreed_said no, "
            "not_agreed_said yes. The pilot's balance question is keyed 10 (the agent's own balance stays at 10).", ""]
    for key, (text, kind) in D.CHECKS.items():
        out.append(f"- **{key}** ({kind}): {text}")
    return "\n".join(out) + "\n"


def main() -> int:
    nx, versions = R.load()
    found = problems(nx, versions)
    for p in found:
        print("PROBLEM", p)
    path = os.path.join(HERE, "CONSTRAINT-texts.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write(texts_md(nx, versions))
    print(f"{len(found)} problems; wrote {os.path.relpath(path, PILOT)}")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
